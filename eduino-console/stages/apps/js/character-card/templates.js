const jong = (s) => {
  const c = (s || "").trim().slice(-1).charCodeAt(0);
  return (
    !isNaN(c) && c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0
  );
}; /* 종성 여부 */
const eul = (s) => (jong(s) ? "을" : "를");
const rago = (s) => (jong(s) ? "이라고" : "라고");
const taught = () =>
  $("classes")
