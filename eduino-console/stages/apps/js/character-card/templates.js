function sugFor(t, k) {
  const base = SUG[t + k] || [],
    cl = taught();
  if (t + k === "0a") return cl.concat(base);
  if (t + k === "1a" && cl.length > 1)
    return [
      cl[0] + eul(cl[0]) + " 자꾸 " + cl[1] + rago(cl[1]) + " 했어요",
    ].concat(base);
  return base;
}
